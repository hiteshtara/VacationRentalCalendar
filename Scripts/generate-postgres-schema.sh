#!/bin/bash
#
# Regenerates the PostgreSQL table definitions FROM the SQLite migrator.
#
#   ./Scripts/generate-postgres-schema.sh
#
# The repositories are the tested business layer, and their SQL is written
# against the SQLite schema. Rather than maintain a second schema by hand and
# hope the two stay compatible, the Postgres tables are derived from the
# authoritative one. The translation is mechanical:
#
#   INTEGER PRIMARY KEY AUTOINCREMENT -> bigint GENERATED ALWAYS AS IDENTITY
#   INTEGER                           -> bigint
#   REAL                              -> double precision
#   TEXT                              -> text
#   BLOB                              -> bytea
#
# Everything Postgres needs that SQLite does not express -- date ranges,
# timestamps, exclusion constraints, the guards, the roles -- lives in
# 011_safety.sql, as generated columns over these same tables. That way the
# repositories keep writing epoch doubles and date pairs while the constraints
# operate on real daterange and timestamptz values.

set -uo pipefail
cd "$(dirname "$0")/.."

OUT="Migrations/postgres/010_repository_schema.sql"
TMP="$(mktemp)"
trap 'rm -f "${TMP}"' EXIT

echo "==> Dumping the authoritative SQLite schema"
swift run vrc-schema-dump > "${TMP}" 2>/dev/null || {
    echo "could not dump the schema — does \`swift run vrc-schema-dump\` work?" >&2
    exit 1
}
tables="$(grep -c 'CREATE TABLE' "${TMP}")"
echo "    ${tables} tables"

echo "==> Translating to PostgreSQL"
python3 - "${TMP}" > "${OUT}" <<'PYEOF'
import re, sys, datetime
src = open(sys.argv[1]).read()
# Parsed by paren depth rather than by a `\n);` terminator. Columns added by a
# later ALTER TABLE appear appended on the final line -- `, time_zone text ...)`
# -- so a line-anchored terminator silently swallowed the following tables into
# the previous block. That produced a schema with tables missing and others
# duplicated, and it applied cleanly enough in SQLite to hide the problem.
def parse_tables(text):
    found = []
    for match in re.finditer(r'CREATE TABLE (\w+)\s*\(', text):
        name = match.group(1)
        start = match.end()          # just after the opening paren
        depth = 1
        index = start
        while index < len(text) and depth > 0:
            if text[index] == '(':
                depth += 1
            elif text[index] == ')':
                depth -= 1
            index += 1
        found.append((name, text[start:index - 1]))
    return found

blocks = parse_tables(src)
skip = {'sqlite_sequence', 'schema_migrations'}

def convert(body):
    out = []
    for line in body.split('\n'):
        l = line
        l = re.sub(r'\bINTEGER PRIMARY KEY AUTOINCREMENT\b',
                   'bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY', l)
        l = re.sub(r'\bINTEGER\b', 'bigint', l)
        l = re.sub(r'\bREAL\b', 'double precision', l)
        l = re.sub(r'\bTEXT\b', 'text', l)
        l = re.sub(r'\bBLOB\b', 'bytea', l)
        out.append(l)
    return '\n'.join(out)

print("""-- VacationRentalCalendar -- PostgreSQL repository schema
--
-- GENERATED by Scripts/generate-postgres-schema.sh from the SQLite migrator.
-- Do not hand-edit the table bodies: they are derived so the two dialects
-- cannot drift apart. Change Sources/VRCCore/Database/Migrations.swift and
-- regenerate.
--
-- These are the tables the tested repositories query, with the same names,
-- columns, nullability and defaults. Identifiers are bigint identity columns
-- rather than uuid, and timestamps stay epoch doubles, precisely so the
-- repositories' SQL runs unchanged. Everything Postgres adds -- date ranges,
-- timestamptz, exclusion constraints, the safety guards -- is in
-- 011_safety.sql as generated columns over these same tables.
--
-- DESIGN REVIEW ONLY. Not applied to any cloud database.

BEGIN;

CREATE TABLE schema_migrations (
    version    bigint PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT now()
);
""")
# PostgreSQL enforces foreign-key targets at CREATE time; SQLite does not. The
# dump is alphabetical, so the tables are topologically sorted here or
# availability_decisions would reference properties before it exists.
kept = [(n, b) for n, b in blocks if n not in skip]
bodies = dict(kept)
names = [n for n, _ in kept]

def dependencies(name):
    refs = set(re.findall(r'REFERENCES\s+(\w+)', bodies[name]))
    return {r for r in refs if r in bodies and r != name}

ordered, placed = [], set()
remaining = list(names)
while remaining:
    ready = [n for n in remaining if dependencies(n) <= placed]
    if not ready:
        # A cycle would need deferred constraints; there are none today, and
        # failing loudly beats emitting something that cannot be applied.
        raise SystemExit("cyclic foreign keys among: %s" % ", ".join(sorted(remaining)))
    for n in sorted(ready):
        ordered.append(n); placed.add(n); remaining.remove(n)

for name in ordered:
    print("CREATE TABLE %s (%s\n);\n" % (name, convert(bodies[name])))
print("INSERT INTO schema_migrations (version) VALUES (10);")
print()
print("COMMIT;")
PYEOF

echo "    wrote ${OUT} ($(grep -c 'CREATE TABLE' "${OUT}") tables, $(wc -l < "${OUT}" | tr -d ' ') lines)"
echo "==> Done. 011_safety.sql is hand-written and is NOT regenerated."
