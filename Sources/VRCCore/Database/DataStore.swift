import Foundation

/// The whole surface the ten repositories use to reach storage.
///
/// Seven methods, deliberately: every repository's SQL already goes through
/// exactly these, so a second backing store is an implementation of this
/// protocol rather than a rewrite of the business rules. `Database` (SQLite,
/// on the Mac) and `DataAPIStore` (Aurora PostgreSQL, in Lambda) both conform,
/// and the repositories cannot tell which they have.
///
/// Synchronous on purpose. Making it async would ripple through every
/// repository and every caller, for no benefit: in a Lambda the handler owns
/// its thread, and on the Mac the work is local. `DataAPIStore` therefore
/// blocks on its transport, which is safe because the runtime loop gives each
/// invocation a thread of its own.
public protocol DataStore: AnyObject, Sendable {
    /// Statements with no parameters and no result. Schema work and pragmas.
    func execute(_ sql: String) throws

    /// A write. Returns the number of affected rows.
    @discardableResult
    func run(_ sql: String, _ parameters: [SQLValue]) throws -> Int

    func query(_ sql: String, _ parameters: [SQLValue]) throws -> [Row]
    func queryOne(_ sql: String, _ parameters: [SQLValue]) throws -> Row?
    func scalarInt(_ sql: String, _ parameters: [SQLValue]) throws -> Int

    /// The id generated by the most recent insert on this connection.
    var lastInsertRowID: Int64 { get }

    /// Runs `body` in a transaction, committing on return and rolling back on
    /// any thrown error. Re-entrant: a nested call joins the outer
    /// transaction rather than starting a second one.
    func transaction<T>(_ body: () throws -> T) throws -> T

    /// Which SQL dialect this store speaks, so the few places that genuinely
    /// differ can ask instead of guessing.
    var dialect: SQLDialect { get }
}

public enum SQLDialect: String, Sendable {
    case sqlite
    case postgres
}

public extension DataStore {
    @discardableResult
    func run(_ sql: String) throws -> Int { try run(sql, []) }
    func query(_ sql: String) throws -> [Row] { try query(sql, []) }
    func queryOne(_ sql: String) throws -> Row? { try queryOne(sql, []) }
    func scalarInt(_ sql: String) throws -> Int { try scalarInt(sql, []) }
}

// Database already has all seven. Declaring conformance costs nothing and is
// what lets the repositories be written against the protocol.
extension Database: DataStore {
    public var dialect: SQLDialect { .sqlite }
}
